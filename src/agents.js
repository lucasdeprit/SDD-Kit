import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { typeAlias } from './profile.js';
import { writeText } from './util.js';

// Files generated for GitHub Copilot in VS Code (SPEC.md section 10):
//  - a marked block in AGENTS.md (or .github/copilot-instructions.md) that always loads
//  - three agent skills in .github/skills/ (open standard: agentskills.io)
// They belong to okw: running `okw init` again regenerates them.

export const BLOCK_START = '<!-- okw:start -->';
export const BLOCK_END = '<!-- okw:end -->';

const SKILLS_DIR = '.github/skills';
const POINTER_FILES = ['AGENTS.md', '.github/copilot-instructions.md'];

export function pointerBlock(wiki) {
  return [
    BLOCK_START,
    '## Project wiki',
    '',
    `This project keeps its knowledge (architecture, patterns, conventions, workflows, testing) in an OKF wiki at \`${wiki}/\`.`,
    '',
    `- Before changing code, read \`${wiki}/index.md\` and the pages relevant to the task (skill \`okf-consult-wiki\`).`,
    '- When a change affects documented rules, patterns or conventions, update the wiki (skill `okf-update-wiki`). Use the `okw` CLI to create pages; never edit `index.md` files by hand or write `verified` entries.',
    '- Never mark a page as reviewed on your own: only a person reviews pages (skill `okf-review-wiki`).',
    BLOCK_END,
    '',
  ].join('\n');
}

const skill = (name, description, body, version) =>
  `---\nname: ${name}\ndescription: ${description}\n---\n<!-- Generated by okw ${version}. Regenerated by "okw init": do not edit. -->\n\n${body.trim()}\n`;

function typeList(profile) {
  return profile.folders.map((f) => `   - \`${typeAlias(f.type)}\` -> \`${f.name}/\` (sections: ${f.sections.map((s) => `\`# ${s}\``).join(', ') || 'none'})`).join('\n');
}

export function skillFiles({ wiki, profile, version }) {
  const consult = skill(
    'okf-consult-wiki',
    'Find project knowledge in the wiki before writing or changing code: architecture, patterns, conventions, workflows and testing rules. Use at the start of any task that touches the codebase.',
    `
# Consult the project wiki

The wiki lives in \`${wiki}/\`. Read only what the task needs.

1. Read \`${wiki}/index.md\`. It lists the folders: overview, architecture, patterns, conventions, workflows, testing, and any optional ones (features, modules, interfaces, operations, troubleshooting).
2. Open the \`index.md\` of the folders that matter for the task, then the pages it points to.
3. For "how do I do X" questions start with \`workflows/\`; each workflow links to the \`patterns/\` it relies on. Rules and structure are in \`architecture/\` and \`conventions/\`; how to run and write tests is in \`testing/\`.
4. Follow what the pages say. If the wiki is silent or contradicts the code, say so instead of guessing, and propose a wiki update (skill \`okf-update-wiki\`).
5. A page without a \`verified\` entry has not been reviewed by a person: use it, but flag the uncertainty when the answer depends on it.
`,
    version,
  );

  const update = skill(
    'okf-update-wiki',
    'Update the project wiki after a change affects documented knowledge, or document something new. Uses the okw CLI so structure and indexes stay correct.',
    `
# Update the project wiki

The wiki lives in \`${wiki}/\`. The \`okw\` CLI does the mechanical work; you only write content.

1. Check whether the change touches knowledge that is already documented. If so, **edit that page in place**. Do not create a duplicate, and do not add a page that only records a decision: put the reason in the page's \`# Why\` section.
2. For new knowledge, create the page with the CLI, not by hand:

   \`okw new <type> <name> --description "<one sentence>" --wiki ${wiki}\`

   It creates the file with its frontmatter and required sections, and registers it in the folder index. Types:

${typeList(profile)}

   \`<name>\` is kebab-case and relative to the folder (for example \`state-management\` or \`bloc/state\`).
3. Fill in every section and delete the \`<!-- TODO -->\` comments. Write in the language the existing pages use.
4. Never edit \`index.md\` files and never write \`verified\` entries: you are not a reviewer. New and edited pages stay unreviewed until a person verifies them.
5. If something no longer applies, set \`status: deprecated\` in that page's frontmatter instead of deleting it.
6. Run \`okw validate --fix --wiki ${wiki}\`, then fix whatever it still reports (it names the file, the rule and how to fix it).
`,
    version,
  );

  const review = skill(
    'okf-review-wiki',
    'Walk a person through the wiki pages nobody has reviewed yet and record their review. Use when asked to review, verify or sign off wiki pages.',
    `
# Review wiki pages with a person

Reviewing is a human act. You prepare the review; the person decides.

1. Run \`okw validate --json --wiki ${wiki}\`. The pages to review are the issues with rule \`frontmatter.verified\` (never reviewed) or \`frontmatter.verified-outdated\` (changed after being verified). The \`review\` field has the totals.
2. Pick one page at a time (ask the person where to start if there are many). Summarise it, check it against the code, and point out anything that looks wrong or missing. Fix problems with the person's agreement.
3. A page with unfilled \`<!-- TODO -->\` comments is not ready: complete it first.
4. Ask the person explicitly whether they confirm the page. Only after a clear yes, run:

   \`okw verify <path> --by human:<id> --wiki ${wiki}\`

   where \`<id>\` identifies that person (ask if you do not know it).
5. Never use a \`human:\` actor for yourself, never verify a page the person has not confirmed, and never write \`verified\` entries by hand.
6. If the person does not confirm a page, leave it as it is and move on.
7. Finish with \`okw validate --wiki ${wiki}\` and report how many pages are still unreviewed.
`,
    version,
  );

  return [
    { path: `${SKILLS_DIR}/okf-consult-wiki/SKILL.md`, text: consult },
    { path: `${SKILLS_DIR}/okf-update-wiki/SKILL.md`, text: update },
    { path: `${SKILLS_DIR}/okf-review-wiki/SKILL.md`, text: review },
  ];
}

// Inserts the block into the file, or replaces it if the markers are already there.
export function upsertBlock(file, block) {
  const text = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (text === null) return { next: block, status: 'created' };
  const start = text.indexOf(BLOCK_START);
  const end = text.indexOf(BLOCK_END);
  let next;
  if (start !== -1 && end > start) {
    next = text.slice(0, start) + block.trimEnd() + text.slice(end + BLOCK_END.length);
  } else {
    next = `${text.replace(/\s+$/, '')}${text.trim() ? '\n\n' : ''}${block}`;
  }
  return { next, status: next === text ? 'unchanged' : 'updated' };
}

// Which file carries the pointer block: the one that already has it, else the
// first that exists, else a new AGENTS.md.
export function pointerFile(projectRoot) {
  const withBlock = POINTER_FILES.find((f) => {
    const p = join(projectRoot, f);
    return existsSync(p) && readFileSync(p, 'utf8').includes(BLOCK_START);
  });
  return withBlock ?? POINTER_FILES.find((f) => existsSync(join(projectRoot, f))) ?? POINTER_FILES[0];
}

// Writes (or refreshes) the agent files. Returns [{ path, status }].
export function writeAgentFiles({ projectRoot, wiki, profile, version }) {
  const results = [];
  const pointer = pointerFile(projectRoot);
  const { next, status } = upsertBlock(join(projectRoot, pointer), pointerBlock(wiki));
  if (status !== 'unchanged') writeText(join(projectRoot, pointer), next);
  results.push({ path: pointer, status });

  for (const file of skillFiles({ wiki, profile, version })) {
    const abs = join(projectRoot, file.path);
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    const fileStatus = current === null ? 'created' : current === file.text ? 'unchanged' : 'updated';
    if (fileStatus !== 'unchanged') writeText(abs, file.text);
    results.push({ path: file.path, status: fileStatus });
  }
  return results;
}
